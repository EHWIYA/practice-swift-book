// 1. 변수(Variable) 생성: 나중에 값을 변경할 수 있습니다.
var name = "Homer" // String(문자열) 타입으로 추론됨 [cite: 19]
name = "Marge"     // 값 변경 가능

// 2. 상수(Constant) 생성: 한 번 정하면 변경이 불가능합니다.
let pi = 3.14      // Double(실수) 타입으로 추론됨 [cite: 56]
//pi = 3.14159     // (오류 발생!) 상수는 값을 다시 할당할 수 없습니다. [cite: 19]

// 3. 타입 명시: 타입을 직접 정해줄 수도 있습니다.
var age: Int = 20  // Int(정수) 타입임을 명시적으로 선언 [cite: 72]
